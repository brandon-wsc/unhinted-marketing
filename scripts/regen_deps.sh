#!/usr/bin/env bash
# Regenerate hash-pinned requirement locks consumed by CI and the Dockerfile.
#
#   scripts/regen_deps.sh          full regen — resolves newest releases that are
#                                  at least 7 days old (release-age gate)
#   scripts/regen_deps.sh --check  re-resolve preserving existing pins; run before
#                                  `git diff --exit-code` to detect stale locks
#
# Locks are universal (all platforms × supported pythons) and carry sha256 hashes,
# so `pip install --require-hashes -r requirements-*.txt` works identically on
# macOS dev machines, Linux CI, and the Docker image — and a same-day malicious
# PyPI release can never be pulled (PYSEC-2026-2 / litellm 1.82.7-8).
set -euo pipefail
cd "$(dirname "$0")/.."

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

# Locked for CPython 3.12 — the version pinned in CI and the Docker image —
# across all platforms. 3.11 is declared in pyproject but unused anywhere.
ARGS=(--universal --python-version 3.12 --generate-hashes --no-header --no-annotate)
if [ "$CHECK" -eq 0 ]; then
    CUTOFF=$(python3 -c 'from datetime import datetime, timedelta, timezone
print((datetime.now(timezone.utc) - timedelta(days=7)).strftime("%Y-%m-%dT%H:%M:%SZ"))')
    ARGS+=(--exclude-newer "$CUTOFF")
fi

# Compile straight onto $out: uv reads the existing file as version preferences
# unless --upgrade, which is what makes --check preserve pins.
lock() {
    local out=$1; shift
    touch "$out"
    uv pip compile "$@" "${ARGS[@]}" -o "$out"
    { echo "# Generated by scripts/regen_deps.sh — do not edit by hand."; cat "$out"; } > "$out.tmp"
    mv "$out.tmp" "$out"
}

lock requirements.txt     pyproject.toml requirements-build.in
lock requirements-dev.txt pyproject.toml requirements-build.in --extra dev
lock requirements-ci.txt  requirements-ci.in
